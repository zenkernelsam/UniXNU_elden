#!/usr/bin/env python3
"""Build all v91 XNU objects from repository inputs, without historical objects."""
from pathlib import Path
import argparse,hashlib,json,subprocess,sys

REPO=Path(__file__).resolve().parents[1]
PROFILE=REPO/'profiles/v91/object-build'

def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--xnu-source',type=Path,required=True,help='xnu/ directory produced by reconstruct_v91.py')
    p.add_argument('--xnu-repository',type=Path,required=True,help='Git checkout containing the pinned original XNU commit')
    p.add_argument('--payload-header',type=Path,required=True,help='Header regenerated by prepare_icon_agent_v91.py')
    p.add_argument('--output',type=Path,required=True);p.add_argument('--jobs',type=int,default=4,choices=range(1,9))
    p.add_argument('--only',help='Optional comma-separated object indices for initial validation')
    a=p.parse_args();plan=json.loads((PROFILE/'plan.json').read_text());xnu=a.xnu_source.resolve(strict=True)
    if plan['format']!=1 or plan['xnu_commit']!='d8b80295118ef25ac3a784134bcf95cd8e88109f':raise RuntimeError('Unexpected profile')
    out=a.output.resolve()
    if out.exists():raise RuntimeError('Output must be a new directory')
    clang=subprocess.check_output(['xcrun','--sdk','iphoneos','--find','clang'],text=True).strip()
    resource=Path(subprocess.check_output([clang,'-print-resource-dir'],text=True).strip())
    old=plan['virtual_root'];files={};toolchain={}
    def expand(value):return value.replace('@VROOT@',old).replace('@CLANG@',clang)
    for name,item in plan['providers'].items():
        if item['kind']=='reconstructed-xnu':base=xnu;source=base/item['path']
        elif item['kind']=='profile-source':base=PROFILE;source=base/item['path']
        elif item['kind']=='external-generated-icon-payload':base=None;source=a.payload_header.resolve(strict=True)
        else:raise RuntimeError('Unknown source provider')
        if base and not source.resolve().is_relative_to(base):raise RuntimeError('Provider escapes source root')
        if sha(source)!=item['sha256']:raise RuntimeError('Source does not match v91: '+str(source))
        files[expand(name)]={'path':str(source),'sha256':item['sha256'],'bytes':source.stat().st_size}
    for name,item in plan['toolchain_files'].items():
        marker='/usr/lib/clang/17/'
        if marker not in name:raise RuntimeError('Unknown toolchain header layout')
        actual=resource/name.split(marker,1)[1]
        if sha(actual)!=item['sha256']:raise RuntimeError('Clang headers differ from the v91 toolchain: '+str(actual))
        toolchain[name]=dict(item,path=str(actual))
    jobs=[]
    for job in plan['jobs']:
        source=expand(job['file']);obj=expand(job['object'])
        arguments=[source if v=='@SOURCE@' else obj if v=='@OUTPUT@' else expand(v) for v in plan['templates'][job['template']]]
        jobs.append({'original_object':obj,'directory':expand(job['directory']),'file':source,
                     'arguments':arguments,'expected_sections':job['expected_sections']})
    capture={'jobs':jobs,'files':files,'toolchain_files':toolchain,'missing':[],'no_dependency_records':[],
             'portable_profile_sha256':sha(PROFILE/'plan.json'),'historical_objects_required':False}
    out.mkdir(parents=True);captured=out/'capture.json';captured.write_text(json.dumps(capture,indent=2)+'\n')
    args=[sys.executable,str(REPO/'tools/replay_xnu_objects.py'),'--capture',str(captured),
          '--historical-root',old,'--output',str(out/'build'),'--payload-header',str(a.payload_header.resolve()),
          '--xnu-repository',str(a.xnu_repository.resolve()),'--jobs',str(a.jobs)]
    if a.only:args+=['--only',a.only]
    subprocess.run(args,check=True)

if __name__=='__main__':main()
