int elden_adc_therm_scale(unsigned port,uint16_t raw,int *mc){
    if(port<1||port>2||!mc)return EldenAdcArgument;
    uint32_t full=port==1?ELDEN_ADC_USB1_FULL_SCALE:ELDEN_ADC_USB2_FULL_SCALE;
    if(raw>=full)return EldenAdcRange;
    int64_t resistance=(int64_t)raw*100000/(full-raw);
    /* Avoid the original interface's implicit s64->s32 wrap at an almost
     * open thermistor. Unknown is safer than publishing a wrapped reading. */
    if(resistance>INT32_MAX)return EldenAdcRange;
    unsigned n=sizeof(adcmap7_100k)/sizeof(adcmap7_100k[0]),i=0;
    while(i<n&&adcmap7_100k[i].x>resistance)++i;
    int value;
    if(!i)value=adcmap7_100k[0].y;
    else if(i==n)value=adcmap7_100k[n-1].y;
    else{
        const struct vadc_map_pt *a=&adcmap7_100k[i-1],*b=&adcmap7_100k[i];
        value=a->y+(int)(((int64_t)b->y-a->y)*(resistance-a->x)/((int64_t)b->x-a->x));
    }
    *mc=value;return 0;
}
