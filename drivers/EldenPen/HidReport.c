int elden_pen_hid_descriptor(uint16_t max,uint8_t *out,size_t capacity,size_t *used){
    const size_t size=sizeof(keyboard)+sizeof(stylus);
    if(!out||!used||(max!=4095&&max!=8191)||capacity<size)return EldenPenArgument;
    uint8_t data[sizeof(keyboard)+sizeof(stylus)];
    for(size_t i=0;i<sizeof(keyboard);++i)data[i]=keyboard[i];
    for(size_t i=0;i<sizeof(stylus);++i)data[sizeof(keyboard)+i]=stylus[i];
    unsigned matches=0;
    for(size_t i=sizeof(keyboard);i+5<size;++i)if(data[i]==0x16&&data[i+1]==0x01&&data[i+2]==0xf0&&data[i+3]==0x26){
        uint16_t min=(uint16_t)(-(int32_t)max);
        data[i+1]=(uint8_t)min;data[i+2]=(uint8_t)(min>>8);
        data[i+4]=(uint8_t)max;data[i+5]=(uint8_t)(max>>8);++matches;
    }
    if(matches!=1)return EldenPenArgument;
    for(size_t i=0;i<size;++i)out[i]=data[i];*used=size;return 0;
}
int elden_pen_hid_report(const EldenPenFrame *f,uint16_t max,uint8_t out[EldenPenHidBytes]){
    if(!f||!out||(max!=4095&&max!=8191))return EldenPenArgument;
    if(f->kind!=EldenPenCoordinate&&f->kind!=EldenPenLeave)return EldenPenUnsupported;
    if(f->x>32767||f->y>32767||f->pressure>max||f->tilt_x< -60||f->tilt_x>60||f->tilt_y< -60||f->tilt_y>60||
       f->tip>1||f->in_range>1||f->buttons>3||f->tip!=(f->pressure!=0)||
       (f->tip&&!f->in_range)||(f->kind==EldenPenLeave&&(f->tip||f->in_range||f->buttons)))return EldenPenRange;
    const uint8_t flags=(uint8_t)(f->tip|((f->buttons&1u)<<1)|(f->in_range<<4)|((f->buttons&2u)<<4));
    const uint8_t data[EldenPenHidBytes]={7,flags,(uint8_t)f->x,(uint8_t)(f->x>>8),(uint8_t)f->y,(uint8_t)(f->y>>8),
        (uint8_t)f->pressure,(uint8_t)(f->pressure>>8),(uint8_t)f->tilt_x,(uint8_t)f->tilt_y};
    for(unsigned i=0;i<EldenPenHidBytes;++i)out[i]=data[i];return 0;
}
int elden_pen_pressure_fixed(int32_t value,int32_t *out){
    if(!out||value<0||value>65536)return EldenPenRange;
    *out=value*EldenPenPressureScale;return 0;
}
